def init_db():
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    c.execute('''
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT UNIQUE NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            security_question TEXT NOT NULL,
            security_answer TEXT NOT NULL,
            farm_region TEXT DEFAULT 'Ashanti Region, Ghana',
            role TEXT DEFAULT 'Smallholder Farmer',
            profile_pic BLOB
        )
    ''')
    
    # Auto-patching columns if upgrading older DB versions
    c.execute("PRAGMA table_info(users)")
    columns = [column[1] for column in c.fetchall()]
    if "role" not in columns:
        c.execute("ALTER TABLE users ADD COLUMN role TEXT DEFAULT 'Smallholder Farmer'")
    if "farm_region" not in columns:
        c.execute("ALTER TABLE users ADD COLUMN farm_region TEXT DEFAULT 'Ashanti Region, Ghana'")
    if "profile_pic" not in columns:
        c.execute("ALTER TABLE users ADD COLUMN profile_pic BLOB")

    c.execute('''
        CREATE TABLE IF NOT EXISTS history (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            username TEXT NOT NULL,
            crop TEXT NOT NULL,
            disease TEXT NOT NULL,
            lang TEXT NOT NULL,
            date_str TEXT NOT NULL,
            time_str TEXT NOT NULL,
            FOREIGN KEY (username) REFERENCES users (username)
        )
    ''')
    conn.commit()
    conn.close()

def hash_password(password):
    return hashlib.sha256(password.encode()).hexdigest()

def add_user(username, email, password, sec_q, sec_a, role):
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    try:
        c.execute(
            "INSERT INTO users (username, email, password, security_question, security_answer, role) VALUES (?, ?, ?, ?, ?, ?)",
            (username, email, hash_password(password), sec_q, sec_a.lower().strip(), role)
        )
        conn.commit()
        conn.close()
        return True
    except sqlite3.IntegrityError:
        conn.close()
        return False

def verify_user(username_or_email, password):
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    c.execute(
        "SELECT * FROM users WHERE (username=? OR email=?) AND password=?", 
        (username_or_email, username_or_email, hash_password(password))
    )
    user = c.fetchone()
    conn.close()
    return user

def reset_password_db(email, sec_answer, new_password):
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    c.execute("SELECT * FROM users WHERE email=? AND security_answer=?", (email, sec_answer.lower().strip()))
    user = c.fetchone()
    if user:
        c.execute("UPDATE users SET password=? WHERE email=?", (hash_password(new_password), email))
        conn.commit()
        conn.close()
        return True
    conn.close()
    return False

def save_diagnosis_to_db(username, crop, disease, lang, date_str, time_str):
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    c.execute(
        "INSERT INTO history (username, crop, disease, lang, date_str, time_str) VALUES (?, ?, ?, ?, ?, ?)",
        (username, crop, disease, lang, date_str, time_str)
    )
    conn.commit()
    conn.close()

def fetch_user_history(username):
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    c.execute("SELECT crop, disease, lang, date_str, time_str FROM history WHERE username=? ORDER BY id DESC", (username,))
    records = c.fetchall()
    conn.close()
    return [{"crop": r[0], "disease": r[1], "lang": r[2], "date": r[3], "time": r[4]} for r in records]

def clear_user_history(username):
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    c.execute("DELETE FROM history WHERE username=?", (username,))
    conn.commit()
    conn.close()

def update_user_profile(old_username, new_username, new_email, farm_region, profile_pic_bytes=None):
    conn = sqlite3.connect("cropguard.db")
    c = conn.cursor()
    try:
        if profile_pic_bytes is not None:
            c.execute(
                "UPDATE users SET username=?, email=?, farm_region=?, profile_pic=? WHERE username=?",
                (new_username, new_email, farm_region, profile_pic_bytes, old_username)
            )
        else:
            c.execute(
                "UPDATE users SET username=?, email=?, farm_region=? WHERE username=?",
                (new_username, new_email, farm_region, old_username)
            )
        c.execute("UPDATE history SET username=? WHERE username=?", (new_username, old_username))
        conn.commit()
        conn.close()
        return True
    except sqlite3.IntegrityError:
        conn.close()
        return False

